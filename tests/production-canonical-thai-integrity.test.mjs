const expected = Object.freeze({
  mallow: { points: 16, bytes: 48, marks: 5, frequencies: [[0x0e48,2],[0x0e31,1],[0x0e35,1],[0x0e4c,1]] },
  pony: { points: 10, bytes: 30, marks: 3, frequencies: [[0x0e49,1],[0x0e48,1],[0x0e31,1]] },
  kyaniteTitle: { points: 8, bytes: 24, marks: 1, frequencies: [[0x0e4c,1]] },
  kyaniteMeaning: { points: 74, bytes: 214, marks: 10, frequencies: [[0x0e48,3],[0x0e31,3],[0x0e34,2],[0x0e37,1],[0x0e35,1]] },
  luckyCloverMeaning: { points: 51, bytes: 149, marks: 10, frequencies: [[0x0e35,3],[0x0e48,2],[0x0e37,1],[0x0e36,1],[0x0e47,1],[0x0e49,1],[0x0e34,1]] }
});

test('canonical Thai codepoint guards preserve approved values', () => {
  for (const [key, value] of Object.entries(canonical)) {
    const rule = expected[key];
    assert.equal(value, String.fromCodePoint(...codepoints(value)), key);
    assert.equal(codepoints(value).length, rule.points, key);
    assert.equal(Buffer.byteLength(value, 'utf8'), rule.bytes, key);
    assert.equal(markCount(value), rule.marks, key);
    for (const [point, occurrences] of rule.frequencies) assert.equal(count(value, point), occurrences, key);
  }
});

test('Kyanite fallback record exactly matches canonical title and meaning', async () => {
  const records = JSON.parse(await readFile(new URL('../data/stones.json', import.meta.url), 'utf8'));
  const kyanite = records.find(record => record.id === 'kyanite');
  assert.ok(kyanite);
  assert.equal(kyanite.nameTh, canonical.kyaniteTitle);
  assert.equal(kyanite.meaningTh, canonical.kyaniteMeaning);
  assert.deepEqual(kyanite.sizes, [10]);
  assert.equal(kyanite.p10, 38);
  assert.equal(kyanite.stockQty, 21);
  assert.equal(kyanite.image, 'assets/Kyanite.webp');
});
