import test from 'node:test';

const from = (...points) => String.fromCodePoint(...points);
const codepoints = value => Array.from(value, ch => ch.codePointAt(0));
const markCount = value => Array.from(value).filter(ch => /\p{Mark}/u.test(ch)).length;
const count = (value, point) => codepoints(value).filter(item => item === point).length;

